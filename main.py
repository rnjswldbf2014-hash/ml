# jepa 월드모델 예제 — 잡음 너머의 세계를 배우고, 머릿속으로 굴려보고 움직이기
#
# 세계: 8칸짜리 고리 위를 좌우로 움직인다.
# 문제: 지금 몇 번 칸인지 직접 알려주지 않는다. 칸마다 정해진 20개 숫자에
#       매번 새로 섞이는 잡음을 얹은 것만 보여준다. 잡음은 원래 못 맞힌다.
#
# 그래서 "다음 관측을 그대로 맞혀라" 는 애초에 불가능한 목표다. 대신 jepa 는
# 요약만 맞히게 시킨다. 요약에는 잡음이 안 들어가니 버리는 게 이득이 되고,
# 결과적으로 요약기가 "지금 몇 번 칸인가" 만 뽑아내게 된다.
#
# 마지막에 그 요약기로 계획을 세운다. 실제로 움직여보기 전에 머릿속으로
# 여러 행동 순서를 굴려보고, 목표에 제일 가까워지는 것을 고른다.
import math
import os
import random
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "rnjswldbf_2014"))
from ml import make, vec, jepa

칸수, 관측수, 요약크기, 잡음 = 8, 20, 12, 0.6
행동들 = ["왼쪽", "오른쪽"]

random.seed(0)
바탕 = [[random.gauss(0, 1) for _ in range(관측수)] for _ in range(칸수)]
rnd = random.Random(1)


def 본다(칸):
    """그 칸을 볼 때 눈에 들어오는 것. 볼 때마다 잡음이 다르다."""
    return [바탕[칸][i] + rnd.gauss(0, 잡음) for i in range(관측수)]


def 켜기(행동):
    return [1.0 if a == 행동 else 0.0 for a in 행동들]


def 움직인다(칸, 행동):
    return (칸 + (1 if 행동 == "오른쪽" else -1)) % 칸수


def 거리(a, b):
    return math.sqrt(sum((x - y) ** 2 for x, y in zip(a, b)))


# ── 1. 만들기 ────────────────────────────────────────────────────────────
# 요약기: 관측 20개 -> 요약 12개
# 예측기: 요약 12개 + 행동 2개 -> 다음 요약 12개
#         (입력 14 - 요약 12 = 2 가 행동 개수로 자동 계산된다)
요약기 = make("world_enc", [관측수, 96], [vec(요약크기)])
예측기 = make("world_prd", [요약크기 + len(행동들), 96], [vec(요약크기)])
세계 = jepa(요약기, 예측기)


# ── 2. 학습 ──────────────────────────────────────────────────────────────
# 정답을 한 개도 안 준다. 그냥 "여기서 이렇게 움직였더니 저렇게 보이더라" 만 준다.
def 겪은일(개수=64):
    지금, 다음, 행동 = [], [], []
    for _ in range(개수):
        칸 = rnd.randrange(칸수)
        a = random.choice(행동들)
        지금.append(본다(칸))
        다음.append(본다(움직인다(칸, a)))
        행동.append(켜기(a))
    return 지금, 다음, 행동


print("배우는 중...")
for i in range(400):
    손실 = 세계.train(*겪은일())
    if i % 100 == 0 or i == 399:
        print(f"  {i+1:4d}번째  손실 {손실:8.4f}")


# ── 3. 각 칸의 요약이 대충 어디쯤인지 기억해둔다 ──────────────────────────
# 요약값은 잡음 때문에 볼 때마다 조금씩 다르다. 여러 번 봐서 평균을 낸다.
def 칸의요약(칸, 횟수=32):
    본것 = [세계.encode(본다(칸)) for _ in range(횟수)]
    return [sum(v[i] for v in 본것) / 횟수 for i in range(요약크기)]


기준 = [칸의요약(c) for c in range(칸수)]


def 어느칸이지(요약):
    """요약이 어느 칸의 것과 제일 비슷한가."""
    return min(range(칸수), key=lambda c: 거리(요약, 기준[c]))


# ── 4. 잡음을 뚫고 지금 위치를 아는가 ────────────────────────────────────
맞음 = sum(어느칸이지(세계.encode(본다(c := rnd.randrange(칸수)))) == c
          for _ in range(300))
print(f"\n지금 몇 번 칸인지 맞히기 : {맞음/3:.1f}%   (찍으면 {100/칸수:.1f}%)")

# 한 걸음 앞을 상상하는가
맞음 = 0
for _ in range(300):
    c = rnd.randrange(칸수)
    a = random.choice(행동들)
    if 어느칸이지(세계.imagine(본다(c), 켜기(a))) == 움직인다(c, a):
        맞음 += 1
print(f"한 걸음 뒤를 상상하기    : {맞음/3:.1f}%")


# ── 5. 머릿속으로 굴려보고 계획 세우기 ───────────────────────────────────
# 여기가 월드모델을 쓰는 이유다. 실제로 움직여보지 않고,
# 요약을 예측기에 계속 넣어서 여러 걸음 앞까지 상상해본다.
def 상상(요약, 행동):
    """요약 + 행동 -> 다음 요약. 실제로 안 움직이고 머릿속에서만."""
    return 예측기.embed(요약 + 켜기(행동), 0)


def 계획(관측, 목표칸, 최대걸음=4):
    """목표 칸에 제일 가까워지는 행동 순서를 찾는다."""
    시작 = 세계.encode(관측)
    최선, 최소 = None, float("inf")
    for n in range(1, 최대걸음 + 1):
        for i in range(2 ** n):
            순서 = [행동들[(i >> k) & 1] for k in range(n)]
            s = 시작
            for a in 순서:
                s = 상상(s, a)
            d = 거리(s, 기준[목표칸])
            if d < 최소:
                최선, 최소 = 순서, d
    return 최선


맞음, 시도 = 0, 60
for _ in range(시도):
    지금칸 = rnd.randrange(칸수)
    목표칸 = rnd.randrange(칸수)
    if 목표칸 == 지금칸:
        목표칸 = (지금칸 + 3) % 칸수

    순서 = 계획(본다(지금칸), 목표칸)

    # 계획대로 실제로 움직여본다
    칸 = 지금칸
    for a in 순서:
        칸 = 움직인다(칸, a)
    if 칸 == 목표칸:
        맞음 += 1

print(f"\n상상만으로 세운 계획이 실제로 목표에 도착 : {맞음}/{시도} = {맞음/시도*100:.1f}%")
print("(실제로 움직여보지 않고, 머릿속에서만 굴려서 고른 행동 순서다)")

세계.save()
print("\n저장했다: world_enc_ml_memory.pth / world_prd_ml_memory.pth")
